import type { OasdiffChange } from '../../src/oasdiff.js';
import type { Files, Git, OpenApiDiffer, PendingChanges, PendingRelease } from '../../src/ports.js';
import type { ChangelogEntry, InterfacePackage } from '../../src/types.js';

/** In-memory {@link Files}. `files.contents` exposes what the code under test wrote. */
export function makeFiles(initial: Record<string, string> = {}): Files & {
  contents: Map<string, string>;
} {
  const contents = new Map(Object.entries(initial));
  return {
    contents,
    read: (path) => Promise.resolve(contents.get(path)),
    write: (path, content) => {
      contents.set(path, content);
      return Promise.resolve();
    },
  };
}

/** In-memory {@link Git}. `refs` maps a ref to the files that exist at it. */
export function makeGit(refs: Record<string, Record<string, string>> = {}): Git {
  return {
    readFileAtRef: (ref, path) => {
      const files = refs[ref];
      if (files === undefined) return Promise.reject(new Error(`unknown ref ${ref}`));
      return Promise.resolve(files[path]);
    },
    tagExists: (tag) => Promise.resolve(tag in refs),
  };
}

/** A differ that returns canned changes and records what it compared. */
export function makeDiffer(changes: readonly OasdiffChange[] = []): OpenApiDiffer & {
  calls: [string, string][];
} {
  const calls: [string, string][] = [];
  return {
    calls,
    changelog: (base, revision) => {
      calls.push([base, revision]);
      return Promise.resolve(changes);
    },
  };
}

export function makePackage(overrides: Partial<InterfacePackage> = {}): InterfacePackage {
  return { name: '@dbp/widget', dir: 'packages/widget', version: '1.2.0', ...overrides };
}

export function makeEntry(overrides: Partial<ChangelogEntry> = {}): ChangelogEntry {
  return { type: 'Added', text: 'A feature.', breaking: false, ...overrides };
}

export function makeRelease(overrides: Partial<PendingRelease> = {}): PendingRelease {
  return {
    name: '@dbp/widget',
    type: 'minor',
    oldVersion: '1.2.0',
    newVersion: '1.3.0',
    entries: [makeEntry()],
    ...overrides,
  };
}

export function makePending(
  releases: readonly PendingRelease[] = [],
  errors: readonly string[] = [],
): PendingChanges {
  return { releases, errors };
}

/** Builds an API Extractor report around the given declarations. */
export function apiReport(body: string): string {
  return [
    '## API Report File for "@dbp/widget"',
    '',
    '> Do not edit this file. It is a report generated by [API Extractor](https://api-extractor.com/).',
    '',
    '```ts',
    '',
    body.trim(),
    '',
    '```',
    '',
  ].join('\n');
}
