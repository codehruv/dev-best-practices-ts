import { describe, expect, it } from 'vitest';

import { renderIndex, renderPage, stampGenerated } from '../../src/render-markdown.ts';

describe('renderPage', () => {
  it('renders header, title, intro, setup, sections, and the link to the test', () => {
    const markdown = renderPage(
      {
        title: 'Title',
        intro: 'Intro.',
        setup: [{ imports: ["import { a } from 'a';"], code: 'a();' }],
        sections: [
          { title: 'Step', prose: 'Prose.', samples: [{ imports: [], code: 'b();' }] },
          { title: 'Bare', prose: '', samples: [{ imports: [], code: 'c();' }] },
        ],
      },
      { path: 'tests/docs/how-to/01-x.test.ts', link: '../../tests/docs/how-to/01-x.test.ts' },
    );

    expect(markdown).toBe(
      [
        '<!-- Generated by @dbp/docs-gen from tests/docs/how-to/01-x.test.ts. Do not edit. Change the source and run `just generate`. -->',
        '# Title',
        'Intro.',
        "```ts\nimport { a } from 'a';\n\na();\n```",
        '## Step',
        'Prose.',
        '```ts\nb();\n```',
        '## Bare',
        '```ts\nc();\n```',
        'Every sample on this page runs as a test in [`01-x.test.ts`](../../tests/docs/how-to/01-x.test.ts).',
      ].join('\n\n') + '\n',
    );
  });
});

describe('renderIndex', () => {
  it('lists every quadrant and marks empty ones', () => {
    const markdown = renderIndex({
      packageName: '@fx/pkg',
      description: 'Does things.',
      tutorials: [{ title: 'Start', href: 'tutorials/start.md' }],
      howTo: [],
      reference: [],
      explanation: [],
    });

    expect(markdown).toContain(
      '## Tutorials\n\nLearning-oriented lessons. Start here.\n\n- [Start](tutorials/start.md)',
    );
    expect(markdown).toContain('## How-to guides');
    expect(markdown).toContain('## Reference');
    expect(markdown).toContain('## Explanation');
    expect(markdown.match(/_None yet._/g)).toHaveLength(3);
  });
});

describe('stampGenerated', () => {
  it('adds the header once', () => {
    const once = stampGenerated('# Ref\n', 'TypeDoc');

    expect(once.startsWith('<!-- Generated by @dbp/docs-gen from TypeDoc.')).toBe(true);
    expect(stampGenerated(once, 'TypeDoc')).toBe(once);
  });
});
