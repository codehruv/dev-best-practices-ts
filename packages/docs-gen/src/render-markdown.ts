import type { CodeSample, DocPage } from './types.ts';

/**
 * The first line of every generated page. Readers and agents see where to make edits,
 * and {@link stampGenerated} uses it to stamp a page only once.
 */
function generatedHeader(source: string): string {
  return `<!-- Generated by @dbp/docs-gen from ${source}. Do not edit. Change the source and run \`just generate\`. -->`;
}

/** Where a page's doc test lives, for its header and its closing link. */
export interface PageSource {
  /** Path relative to the package root, shown in the generated header. */
  readonly path: string;
  /** Path relative to the page, so readers can open the test that proves the samples. */
  readonly link: string;
}

/** Renders a parsed doc test as a markdown page. */
export function renderPage(page: DocPage, source: PageSource): string {
  const blocks = [
    generatedHeader(source.path),
    `# ${page.title}`,
    page.intro,
    ...page.setup.map(renderSample),
  ];
  for (const section of page.sections) {
    blocks.push(`## ${section.title}`, section.prose, ...section.samples.map(renderSample));
  }
  blocks.push(
    `Every sample on this page runs as a test in [\`${basename(source.path)}\`](${source.link}).`,
  );
  return joinBlocks(blocks);
}

/** A link to one page in the docs index. */
export interface PageLink {
  readonly title: string;
  /** Path relative to the docs directory. */
  readonly href: string;
}

/** The pages in each Diátaxis quadrant, for the package docs index. */
interface DocsIndex {
  readonly packageName: string;
  readonly description: string;
  readonly tutorials: readonly PageLink[];
  readonly howTo: readonly PageLink[];
  /** Absent when the package has no generated API reference. */
  readonly reference?: PageLink;
  readonly explanation: readonly PageLink[];
}

/** Renders `docs/README.md`, the entry point that links the four quadrants. */
export function renderIndex(index: DocsIndex): string {
  const quadrant = (heading: string, purpose: string, links: readonly PageLink[]): string[] => [
    `## ${heading}`,
    purpose,
    links.length === 0
      ? '_None yet._'
      : links.map((link) => `- [${link.title}](${link.href})`).join('\n'),
  ];
  return joinBlocks([
    generatedHeader('tests/docs and docs/explanation'),
    `# ${index.packageName}`,
    index.description,
    ...quadrant('Tutorials', 'Learning-oriented lessons. Start here.', index.tutorials),
    ...quadrant('How-to guides', 'Task-oriented recipes for real problems.', index.howTo),
    ...quadrant(
      'Reference',
      'Information-oriented description of every export.',
      index.reference === undefined ? [] : [index.reference],
    ),
    ...quadrant(
      'Explanation',
      'Understanding-oriented background and design reasoning.',
      index.explanation,
    ),
  ]);
}

/** Prepends the generated header unless the page already starts with one. */
export function stampGenerated(markdown: string, source: string): string {
  const header = generatedHeader(source);
  return markdown.startsWith(header) ? markdown : `${header}\n\n${markdown}`;
}

function renderSample(sample: CodeSample): string {
  const imports = sample.imports.length === 0 ? '' : `${sample.imports.join('\n')}\n\n`;
  return `\`\`\`ts\n${imports}${sample.code}\n\`\`\``;
}

function joinBlocks(blocks: readonly string[]): string {
  return `${blocks.filter((block) => block.trim() !== '').join('\n\n')}\n`;
}

function basename(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}
