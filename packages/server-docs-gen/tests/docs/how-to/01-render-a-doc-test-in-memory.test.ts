/**
 * Parse and render a doc test without touching the file system, for example to preview a
 * page in an editor extension or to render doc tests into another site generator.
 * `parseDocTest` returns the page structure, and `renderPage` turns it into markdown.
 */
import {
  type CodeSample,
  type DocPage,
  type DocSection,
  type PageSource,
  parseDocTest,
  renderPage,
} from '@dbp/server-docs-gen';
import { describe, expect, it } from 'vitest';

// #region source
const source = [
  "import { describe, it } from 'vitest';",
  "import { greet } from '@demo/greet';",
  '',
  "describe('Greet a team', () => {",
  '  /** Greet each member in turn. */',
  "  it('Greet everyone', () => {",
  "    for (const name of ['Ada', 'Grace']) greet(name);",
  '  });',
  '});',
].join('\n');
// #endregion source

describe('Render a doc test in memory', () => {
  /**
   * The page mirrors the test: one section per `it`, one sample per region (or the whole
   * test body when there are no regions). Each sample carries only the imports it uses,
   * and never the test framework's.
   */
  it('Parse the page structure', () => {
    // #region parse
    const page: DocPage = parseDocTest(source, 'tests/docs/how-to/01-greet-a-team.test.ts');
    const section: DocSection | undefined = page.sections[0];
    const sample: CodeSample | undefined = section?.samples[0];
    // page.title: 'Greet a team', section.title: 'Greet everyone'
    // sample.imports: ["import { greet } from '@demo/greet';"]
    // #endregion parse

    expect(page.title).toBe('Greet a team');
    expect(section?.title).toBe('Greet everyone');
    expect(sample?.imports).toEqual(["import { greet } from '@demo/greet';"]);
    expect(sample?.code).toBe("for (const name of ['Ada', 'Grace']) greet(name);");
  });

  /**
   * `renderPage` needs to know where the test lives: `path` from the package root for the
   * generated header, and `link` from the page, for the closing link to the test.
   */
  it('Render the markdown', () => {
    // #region render
    const page = parseDocTest(source, 'tests/docs/how-to/01-greet-a-team.test.ts');
    const where: PageSource = {
      path: 'tests/docs/how-to/01-greet-a-team.test.ts',
      link: '../../tests/docs/how-to/01-greet-a-team.test.ts',
    };
    const markdown = renderPage(page, where);
    // #endregion render

    expect(markdown).toContain('# Greet a team\n\n## Greet everyone\n\nGreet each member in turn.');
    expect(
      markdown.startsWith('<!-- Generated by @dbp/server-docs-gen from tests/docs/how-to/'),
    ).toBe(true);
  });
});
