import { describe, expect, it } from 'vitest';

import { checkDocsTree } from '../../src/check-docs-tree.ts';
import { makePackage } from './fixtures.ts';

const HEADER = '<!-- Generated by @dbp/server-docs-gen from x. Do not edit. -->';
const INDEX = [
  HEADER,
  '# @fx/pkg',
  '## Tutorials',
  '- [Start](tutorials/start.md)',
  '## How-to guides',
  '## Reference',
  '## Explanation',
  '- [Why](explanation/why.md)',
].join('\n\n');
const TUTORIAL = `${HEADER}\n\n# Start\n\n\`\`\`ts\nrun();\n\`\`\`\n`;
const EXPLANATION = '# Why it works\n\nBecause.\n';

function treeWith(files: Record<string, string>): ReturnType<typeof checkDocsTree> {
  const fixture = makePackage({
    'docs/README.md': INDEX,
    'docs/tutorials/start.md': TUTORIAL,
    'docs/explanation/why.md': EXPLANATION,
    ...files,
  });
  return checkDocsTree(fixture.dir);
}

describe('checkDocsTree', () => {
  it('passes a well-formed tree', () => {
    expect(treeWith({})).toEqual({ brokenLinks: [], compliance: [] });
  });

  it('reports a missing index without checking further', () => {
    const fixture = makePackage({ 'docs/tutorials/start.md': TUTORIAL });

    expect(checkDocsTree(fixture.dir).compliance).toEqual([
      'docs/README.md is missing. Run `just generate`.',
    ]);
  });

  it('reports links to missing files and missing anchors, and ignores external links', () => {
    const report = treeWith({
      'docs/explanation/why.md': [
        '# Why it works',
        '[ok](../tutorials/start.md#start) [here](#why-it-works) [web](https://example.com)',
        '[gone](missing.md) [bad anchor](../tutorials/start.md#nope)',
      ].join('\n'),
    });

    expect(report.brokenLinks).toEqual([
      'docs/explanation/why.md:3: ../tutorials/start.md#nope has no #nope anchor.',
      'docs/explanation/why.md:3: missing.md points to a missing file.',
    ]);
  });

  it('reports pages outside a quadrant and pages nothing links to', () => {
    const report = treeWith({
      'docs/notes.md': '# Notes\n',
      'docs/explanation/hidden.md': '# Hidden\n',
    });

    expect(report.compliance).toEqual([
      'docs/explanation/hidden.md: orphan page. Nothing links to it from docs/README.md.',
      'docs/notes.md: belongs to no quadrant. Move it under docs/{tutorials,how-to,reference,explanation}/.',
      'docs/notes.md: orphan page. Nothing links to it from docs/README.md.',
    ]);
  });

  it('reports an index missing a quadrant', () => {
    const report = treeWith({ 'docs/README.md': INDEX.replace('## How-to guides', '') });

    expect(report.compliance).toContain('docs/README.md: missing the "How-to guides" quadrant.');
  });

  it.each([
    {
      name: 'a hand-written tutorial',
      page: '# Start\n\n```ts\nrun();\n```\n',
      file: 'docs/tutorials/start.md',
      problem: 'tutorials pages are generated',
    },
    {
      name: 'a tutorial without code',
      page: `${HEADER}\n\n# Start\n\nJust prose.\n`,
      file: 'docs/tutorials/start.md',
      problem: 'tutorials pages need at least 1 code sample(s).',
    },
    {
      name: 'a tutorial with migration content',
      page: `${HEADER}\n\n# Start\n\n## Migrate from v1\n\n\`\`\`ts\nrun();\n\`\`\`\n`,
      file: 'docs/tutorials/start.md',
      problem: 'heading "Migrate from v1" contains "migrate"',
    },
    {
      name: 'an explanation titled like a how-to',
      page: '# How to retry\n',
      file: 'docs/explanation/why.md',
      problem: 'a explanation title cannot start with "how to"',
    },
    {
      name: 'a code-heavy explanation',
      page: '# Why it works\n\n```ts\na\n```\n\n```ts\nb\n```\n\n```ts\nc\n```\n',
      file: 'docs/explanation/why.md',
      problem: '3 code blocks. explanation pages allow 2.',
    },
    {
      name: 'a generated explanation',
      page: `${HEADER}\n\n# Why it works\n`,
      file: 'docs/explanation/why.md',
      problem: 'explanation pages are hand-written',
    },
    {
      name: 'a page with two titles',
      page: '# Why it works\n\n# Again\n',
      file: 'docs/explanation/why.md',
      problem: 'needs exactly one "# " title, found 2.',
    },
  ])('reports $name', ({ page, file, problem }) => {
    const report = treeWith({ [file]: page });

    expect(report.compliance.join('\n')).toContain(`${file}: ${problem}`);
  });
});
