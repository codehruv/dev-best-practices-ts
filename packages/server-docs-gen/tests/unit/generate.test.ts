import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { generateDocs } from '../../src/generate.ts';
import { docTest, makePackage } from './fixtures.ts';

const step = docTest({ title: 'Getting started', body: "  it('Run', () => {\n    run();\n  });" });

describe('generateDocs', () => {
  it('writes pages ordered by their numeric prefix and an index of every quadrant', async () => {
    const fixture = makePackage({
      'tests/docs/how-to/02-second.test.ts': docTest({
        title: 'Second task',
        body: "  it('Do', () => {\n    b();\n  });",
      }),
      'tests/docs/how-to/01-first.test.ts': docTest({
        title: 'First task',
        body: "  it('Do', () => {\n    a();\n  });",
      }),
      'tests/docs/tutorials/01-start.test.ts': step,
      'docs/explanation/why.md': '# Why it exists\n\nBecause.\n',
    });

    const written = await generateDocs(fixture.dir);

    expect(written).toEqual([
      'docs/tutorials/start.md',
      'docs/how-to/first.md',
      'docs/how-to/second.md',
      'docs/README.md',
    ]);
    const index = readFileSync(join(fixture.dir, 'docs/README.md'), 'utf8');
    expect(index.indexOf('[First task]')).toBeLessThan(index.indexOf('[Second task]'));
    expect(index).toContain('- [Why it exists](explanation/why.md)');
    expect(readFileSync(join(fixture.dir, 'docs/explanation/why.md'), 'utf8')).toBe(
      '# Why it exists\n\nBecause.\n',
    );
  });

  it('deletes pages whose doc test no longer exists', async () => {
    const fixture = makePackage({
      'tests/docs/tutorials/01-start.test.ts': step,
      'docs/tutorials/removed.md': 'stale',
    });

    await generateDocs(fixture.dir);

    expect(existsSync(join(fixture.dir, 'docs/tutorials/removed.md'))).toBe(false);
    expect(existsSync(join(fixture.dir, 'docs/tutorials/start.md'))).toBe(true);
  });

  it('stamps TypeDoc pages once and links the reference from the index', async () => {
    const fixture = makePackage({ 'docs/reference/README.md': '# API\n' });

    await generateDocs(fixture.dir);
    await generateDocs(fixture.dir);

    const reference = readFileSync(join(fixture.dir, 'docs/reference/README.md'), 'utf8');
    expect(reference.match(/Generated by @dbp\/server-docs-gen/g)).toHaveLength(1);
    expect(readFileSync(join(fixture.dir, 'docs/README.md'), 'utf8')).toContain(
      '- [API reference](reference/README.md)',
    );
  });

  it('writes a specification page per feature, links it under Reference, and drops stale ones', async () => {
    const fixture = makePackage({
      'docs/reference/README.md': '# API\n',
      'docs/reference/specifications/removed.md': 'stale',
      'features/greet.feature':
        'Feature: Greet people\n\n  @REQ-001\n  Scenario: Greet\n    Given a\n',
    });

    const written = await generateDocs(fixture.dir);

    expect(written).toContain('docs/reference/specifications/greet.md');
    expect(existsSync(join(fixture.dir, 'docs/reference/specifications/removed.md'))).toBe(false);
    const page = readFileSync(join(fixture.dir, 'docs/reference/specifications/greet.md'), 'utf8');
    expect(page).toContain('# Greet people');
    expect(page).toContain(
      '[`greet.feature.test.ts`](../../../tests/features/greet.feature.test.ts)',
    );
    const index = readFileSync(join(fixture.dir, 'docs/README.md'), 'utf8');
    expect(index).toContain(
      '- [API reference](reference/README.md)\n- [Greet people](reference/specifications/greet.md)',
    );
  });

  it('is deterministic', async () => {
    const fixture = makePackage({ 'tests/docs/tutorials/01-start.test.ts': step });

    await generateDocs(fixture.dir);
    const first = readFileSync(join(fixture.dir, 'docs/tutorials/start.md'), 'utf8');
    await generateDocs(fixture.dir);

    expect(readFileSync(join(fixture.dir, 'docs/tutorials/start.md'), 'utf8')).toBe(first);
  });
});
