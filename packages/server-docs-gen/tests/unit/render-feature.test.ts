import { describe, expect, it } from 'vitest';

import { outlineMarkdown } from '../../src/markdown.ts';
import { parseFeature } from '../../src/parse-feature.ts';
import { renderFeaturePage } from '../../src/render-feature.ts';

const SOURCE = {
  path: 'features/greet.feature',
  link: '../../../features/greet.feature',
  testLink: '../../../tests/features/greet.feature.test.ts',
};

function render(feature: string): string {
  return renderFeaturePage(parseFeature(feature, SOURCE.path), SOURCE);
}

describe('renderFeaturePage', () => {
  const markdown = render(
    [
      'Feature: Greet people',
      '  Greets by name.',
      '',
      '  Background:',
      '    Given a greeter',
      '',
      '  @REQ-002',
      '  Scenario: Requirements',
      '    When I greet "A|B"',
      '',
      '  @REQ-001 @REQ-002',
      '  Scenario: Greet twice',
      '    Then the log reads:',
      '      | name |',
      '      | Ada  |',
      '',
    ].join('\n'),
  );

  it('opens with the generated header, title, description, and a sorted requirements table', () => {
    expect(markdown).toMatch(
      /^<!-- Generated by @dbp\/server-docs-gen from features\/greet\.feature\./,
    );
    expect(markdown).toContain('# Greet people\n\nGreets by name.\n\n## Requirements');
    expect(markdown).toContain(
      [
        '| Requirement | Verified by |',
        '| --- | --- |',
        '| <a id="req-001"></a>`REQ-001` | [Greet twice](#greet-twice) |',
        '| <a id="req-002"></a>`REQ-002` | [Requirements](#requirements-1), [Greet twice](#greet-twice) |',
      ].join('\n'),
    );
  });

  it('renders the background, each scenario, its requirement links, and step arguments', () => {
    expect(markdown).toContain(
      '## Background\n\nEvery scenario starts with these steps.\n\n- **Given** a greeter',
    );
    expect(markdown).toContain(
      '## Greet twice\n\nVerifies [`REQ-001`](#req-001), [`REQ-002`](#req-002).\n\n- **Then** the log reads:\n\n  | name |\n  | --- |\n  | Ada |',
    );
  });

  it('links only anchors the page defines', () => {
    const outline = outlineMarkdown(markdown);
    const fragments = outline.links
      .map((link) => link.href)
      .filter((href) => href.startsWith('#'))
      .map((href) => href.slice(1));

    expect(fragments.length).toBeGreaterThan(0);
    expect(fragments.filter((fragment) => !outline.anchors.has(fragment))).toEqual([]);
  });

  it('closes with links to the step definitions and the feature file', () => {
    expect(markdown.trimEnd().split('\n').at(-1)).toBe(
      'Every scenario on this page runs as a test in [`greet.feature.test.ts`](../../../tests/features/greet.feature.test.ts). The source is [`greet.feature`](../../../features/greet.feature).',
    );
  });

  it('says so when no scenario names a requirement, and renders outline examples', () => {
    const outline = render(
      [
        'Feature: F',
        '  Scenario Outline: Greet <name>',
        '    When I greet "<name>"',
        '',
        '    Examples:',
        '      | name |',
        '      | Ada  |',
        '',
      ].join('\n'),
    );

    expect(outline).toContain('## Requirements\n\n_No scenario names a requirement._');
    expect(outline).toContain('Examples:\n\n| name |\n| --- |\n| Ada |');
  });
});
