import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';

import { type MarkdownOutline, outlineMarkdown } from './markdown.ts';

const GENERATED_MARKER = '<!-- Generated by @dbp/server-docs-gen';

/** The four Diátaxis quadrants, each a directory under `docs/`. */
const QUADRANTS = ['tutorials', 'how-to', 'reference', 'explanation'] as const;
type Quadrant = (typeof QUADRANTS)[number];

/** The index heading that introduces each quadrant in `docs/README.md`. */
const INDEX_HEADINGS: Record<Quadrant, string> = {
  tutorials: 'Tutorials',
  'how-to': 'How-to guides',
  reference: 'Reference',
  explanation: 'Explanation',
};

/**
 * Per-quadrant purity rules. Diátaxis fails in practice when one page tries to serve two
 * needs, such as a tutorial that turns into a migration guide, so each quadrant rejects
 * the content that belongs to another.
 */
interface QuadrantRule {
  /** Generated quadrants reject hand-written pages, which the next `just generate` deletes. */
  readonly generated: boolean;
  readonly minCodeBlocks: number;
  readonly maxCodeBlocks: number;
  /** Lowercase prefixes the page title must not start with. */
  readonly forbiddenTitlePrefixes: readonly string[];
  /** Lowercase words no heading may contain. */
  readonly forbiddenHeadingWords: readonly string[];
}

const RULES: Record<Quadrant, QuadrantRule> = {
  tutorials: {
    generated: true,
    minCodeBlocks: 1,
    maxCodeBlocks: Number.POSITIVE_INFINITY,
    forbiddenTitlePrefixes: ['why', 'about', 'how to', 'reference'],
    forbiddenHeadingWords: ['migrate', 'migration', 'upgrade', 'troubleshoot', 'troubleshooting'],
  },
  'how-to': {
    generated: true,
    minCodeBlocks: 1,
    maxCodeBlocks: Number.POSITIVE_INFINITY,
    forbiddenTitlePrefixes: ['why', 'about', 'understanding', 'introduction', 'getting started'],
    forbiddenHeadingWords: [],
  },
  reference: {
    generated: true,
    minCodeBlocks: 0,
    maxCodeBlocks: Number.POSITIVE_INFINITY,
    forbiddenTitlePrefixes: [],
    forbiddenHeadingWords: [],
  },
  explanation: {
    generated: false,
    minCodeBlocks: 0,
    // Explanation discusses. A page that needs more code than this is a how-to guide.
    maxCodeBlocks: 2,
    forbiddenTitlePrefixes: ['how to', 'getting started', 'tutorial', 'step'],
    forbiddenHeadingWords: ['step'],
  },
};

/** Problems found in a package's `docs/` tree. Every entry names the file it is about. */
export interface DocsTreeReport {
  /** Relative links whose target file or `#anchor` does not exist. */
  readonly brokenLinks: readonly string[];
  /** Diátaxis structure and quadrant-purity violations. */
  readonly compliance: readonly string[];
}

/**
 * Checks every markdown file under `<packageDir>/docs`, generated and hand-written alike:
 * link integrity (file and anchor), one quadrant per page, quadrant purity, a complete
 * index, and no page unreachable from `docs/README.md`.
 */
export function checkDocsTree(packageDir: string): DocsTreeReport {
  const root = resolve(packageDir);
  const docsDir = join(root, 'docs');
  const brokenLinks: string[] = [];
  const compliance: string[] = [];

  if (!existsSync(join(docsDir, 'README.md'))) {
    return { brokenLinks, compliance: ['docs/README.md is missing. Run `just generate`.'] };
  }

  const files = listMarkdown(docsDir);
  const outlines = new Map<string, MarkdownOutline>();
  for (const file of files) {
    outlines.set(file, outlineMarkdown(readFileSync(file, 'utf8')));
  }
  const show = (file: string): string => relative(root, file);

  for (const [file, outline] of outlines) {
    for (const link of outline.links) {
      const problem = checkLink(file, link.href, outlines);
      if (problem !== undefined) {
        brokenLinks.push(`${show(file)}:${link.line}: ${link.href} ${problem}`);
      }
    }

    if (file === join(docsDir, 'README.md')) {
      continue;
    }
    const quadrant = quadrantOf(docsDir, file);
    if (quadrant === undefined) {
      compliance.push(
        `${show(file)}: belongs to no quadrant. Move it under docs/{${QUADRANTS.join(',')}}/.`,
      );
      continue;
    }
    compliance.push(...checkPurity(show(file), quadrant, outline, readFileSync(file, 'utf8')));
  }

  const index = outlines.get(join(docsDir, 'README.md'));
  const indexHeadings = new Set(index?.headings.map((heading) => heading.text) ?? []);
  for (const quadrant of QUADRANTS) {
    if (!indexHeadings.has(INDEX_HEADINGS[quadrant])) {
      compliance.push(`docs/README.md: missing the "${INDEX_HEADINGS[quadrant]}" quadrant.`);
    }
  }

  const reachable = reachableFrom(join(docsDir, 'README.md'), outlines);
  for (const file of files) {
    if (!reachable.has(file)) {
      compliance.push(`${show(file)}: orphan page. Nothing links to it from docs/README.md.`);
    }
  }

  return { brokenLinks: brokenLinks.sort(byNatural), compliance: compliance.sort(byNatural) };
}

// Sorts `file:28` before `file:116`.
function byNatural(a: string, b: string): number {
  return a.localeCompare(b, 'en', { numeric: true });
}

function checkPurity(
  shown: string,
  quadrant: Quadrant,
  outline: MarkdownOutline,
  markdown: string,
): string[] {
  const rule = RULES[quadrant];
  const problems: string[] = [];
  const isGenerated =
    markdown.startsWith(GENERATED_MARKER) || markdown.includes(`\n${GENERATED_MARKER}`);
  if (rule.generated && !isGenerated) {
    problems.push(`${shown}: ${quadrant} pages are generated. Write a doc test or TSDoc instead.`);
  }
  if (!rule.generated && isGenerated) {
    problems.push(
      `${shown}: ${quadrant} pages are hand-written, but this one carries a generated header.`,
    );
  }

  const titles = outline.headings.filter((heading) => heading.depth === 1);
  const [title, ...extraTitles] = titles;
  if (title === undefined || extraTitles.length > 0) {
    problems.push(`${shown}: needs exactly one "# " title, found ${titles.length}.`);
  }
  const lowerTitle = title?.text.toLowerCase() ?? '';
  const badPrefix = rule.forbiddenTitlePrefixes.find((prefix) => lowerTitle.startsWith(prefix));
  if (badPrefix !== undefined) {
    problems.push(
      `${shown}: a ${quadrant} title cannot start with "${badPrefix}". It reads as another quadrant.`,
    );
  }
  for (const heading of outline.headings) {
    const words = heading.text.toLowerCase().split(/[^\p{L}]+/u);
    const badWord = rule.forbiddenHeadingWords.find((word) => words.includes(word));
    if (badWord !== undefined) {
      problems.push(
        `${shown}: heading "${heading.text}" contains "${badWord}", which belongs in another quadrant.`,
      );
    }
  }
  if (outline.codeBlockCount < rule.minCodeBlocks) {
    problems.push(
      `${shown}: ${quadrant} pages need at least ${rule.minCodeBlocks} code sample(s).`,
    );
  }
  if (outline.codeBlockCount > rule.maxCodeBlocks) {
    problems.push(
      `${shown}: ${outline.codeBlockCount} code blocks. ${quadrant} pages allow ${rule.maxCodeBlocks}. Move the procedure to a how-to guide.`,
    );
  }
  return problems;
}

function checkLink(
  file: string,
  href: string,
  outlines: ReadonlyMap<string, MarkdownOutline>,
): string | undefined {
  if (/^[a-z][a-z0-9+.-]*:/i.test(href)) {
    return undefined; // http:, https:, mailto:. External links are out of scope.
  }
  const [pathPart = '', fragment] = href.split('#');
  const target = pathPart === '' ? file : resolve(dirname(file), decodeURIComponent(pathPart));
  if (!existsSync(target)) {
    return 'points to a missing file.';
  }
  if (fragment === undefined || fragment === '') {
    return undefined;
  }
  const outline = outlines.get(target);
  if (outline === undefined) {
    return target.endsWith('.md') ? 'points into a page outside docs/.' : undefined;
  }
  return outline.anchors.has(decodeURIComponent(fragment))
    ? undefined
    : `has no #${fragment} anchor.`;
}

function reachableFrom(start: string, outlines: ReadonlyMap<string, MarkdownOutline>): Set<string> {
  const seen = new Set<string>([start]);
  const queue = [start];
  for (let file = queue.shift(); file !== undefined; file = queue.shift()) {
    for (const link of outlines.get(file)?.links ?? []) {
      const pathPart = link.href.split('#')[0] ?? '';
      if (pathPart === '' || /^[a-z][a-z0-9+.-]*:/i.test(pathPart)) {
        continue;
      }
      const target = resolve(dirname(file), decodeURIComponent(pathPart));
      if (outlines.has(target) && !seen.has(target)) {
        seen.add(target);
        queue.push(target);
      }
    }
  }
  return seen;
}

function quadrantOf(docsDir: string, file: string): Quadrant | undefined {
  const [first, ...rest] = relative(docsDir, file).split(sep);
  return rest.length > 0 ? QUADRANTS.find((quadrant) => quadrant === first) : undefined;
}

function listMarkdown(dir: string): string[] {
  return readdirSync(dir)
    .flatMap((entry) => {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) {
        return listMarkdown(path);
      }
      return entry.endsWith('.md') ? [path] : [];
    })
    .sort();
}
